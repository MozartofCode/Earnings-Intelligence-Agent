#!/usr/bin/env python3
"""Render an earnings-desk report JSON into the shared HTML template (and Markdown).

Usage
  python3 render_report.py report.json [--out-dir earnings-desk-reports] [--no-md]
  cat report.json | python3 render_report.py - --out-dir earnings-desk-reports

Prints JSON: {"html": path, "markdown": path}. See ../references/report-schema.md
for the full schema. Minimal example:

{
  "skill": "earnings-recap", "ticker": "NVDA", "company": "NVIDIA Corp", "exchange": "Nasdaq",
  "date": "2026-11-16", "title": "Another *beat-and-raise*", "subtitle": "Q2 FY27 results",
  "verdict": {"label": "Print quality", "value": "Strong", "sub": "beat + raise", "tone": "pos"},
  "kpis": [{"label": "Revenue", "value": "$96.2B", "delta": "+106% y/y", "tone": "pos"}],
  "summary": "Markdown paragraph(s)...",
  "sections": [{"heading": "...", "kicker": "...", "body": "markdown", "callouts": [...],
                "scores": [...], "tables": [{"columns": [...], "rows": [[...]]}],
                "charts": [{"type": "bar", "title": "...", "labels": [...], "datasets": [{"label": "...", "data": [...]}]}]}],
  "sources": [{"label": "10-Q filed 2026-08-27", "url": "https://www.sec.gov/..."}]
}
"""
import argparse
import json
import os
import re
import sys
from datetime import date

HERE = os.path.dirname(os.path.abspath(__file__))
TEMPLATE = os.path.join(HERE, "..", "assets", "report-template.html")
TONES = {"pos", "neg", "warn", "neutral", "accent"}


def validate(d):
    problems = []
    for k in ("skill", "title"):
        if not d.get(k):
            problems.append("missing '%s'" % k)
    for i, s in enumerate(d.get("sections", [])):
        if not s.get("heading"):
            problems.append("sections[%d] missing 'heading'" % i)
        for t in s.get("tables", []) + ([s["table"]] if s.get("table") else []):
            n = len(t.get("columns", []))
            for j, r in enumerate(t.get("rows", [])):
                if len(r) != n:
                    problems.append("sections[%d] table row %d has %d cells, expected %d" % (i, j, len(r), n))
    for k in d.get("kpis", []):
        if k.get("tone") and k["tone"] not in TONES:
            problems.append("kpi '%s' has unknown tone '%s'" % (k.get("label"), k["tone"]))
    if not d.get("sources"):
        problems.append("no 'sources' (every report must cite where its numbers came from)")
    return problems


def cell(c):
    return c.get("text", "") if isinstance(c, dict) else ("" if c is None else str(c))


def to_markdown(d):
    L = []
    head = "%s · %s" % (d.get("ticker"), d.get("company")) if d.get("ticker") else ""
    L.append("# %s" % re.sub(r"\*(.+?)\*", r"\1", d.get("title", "")))
    if head:
        L.append("**%s** · `/%s` · %s" % (head, d.get("skill"), d.get("date", "")))
    if d.get("subtitle"):
        L.append("_%s_" % d["subtitle"])
    v = d.get("verdict")
    if v:
        L.append("> **%s: %s**%s" % (v.get("label", "Verdict"), v.get("value"), (" (%s)" % v["sub"]) if v.get("sub") else ""))
    if d.get("kpis"):
        L.append("\n".join([
            "| " + " | ".join(k["label"] for k in d["kpis"]) + " |",
            "|" + "---|" * len(d["kpis"]),
            "| " + " | ".join("%s%s" % (k["value"], (" (%s)" % k["delta"]) if k.get("delta") else "") for k in d["kpis"]) + " |"]))
    if d.get("summary"):
        L.append("## The short version\n\n" + d["summary"])
    for s in d.get("sections", []):
        L.append("## " + s["heading"])
        if s.get("callouts"):
            L.append("\n".join("- **%s**: %s" % (c.get("title"), c.get("body")) for c in s["callouts"]))
        if s.get("body"):
            L.append(s["body"])
        if s.get("scores"):
            L.append("\n".join("- %s: **%s**" % (sc.get("name"), sc.get("value")) for sc in s["scores"]))
        for t in s.get("tables", []) + ([s["table"]] if s.get("table") else []):
            if t.get("caption"):
                L.append("**%s**" % t["caption"])
            tl = ["| " + " | ".join(t["columns"]) + " |", "|" + "---|" * len(t["columns"])]
            tl += ["| " + " | ".join(cell(c).replace("|", "\\|") for c in r) + " |" for r in t.get("rows", [])]
            L.append("\n".join(tl))
        for ch in s.get("charts", []) + ([s["chart"]] if s.get("chart") else []):
            L.append("_Chart: %s (see HTML report)_" % ch.get("title", ""))
        if s.get("after"):
            L.append(s["after"])
    if d.get("sources"):
        L.append("## Sources")
        src = []
        for i, s in enumerate(d["sources"], 1):
            if isinstance(s, dict):
                src.append("%d. [%s](%s)" % (i, s.get("label") or s.get("url"), s.get("url")) if s.get("url") else "%d. %s" % (i, s.get("label")))
            else:
                src.append("%d. %s" % (i, s))
        L.append("\n".join(src))
    L.append("\n---\n_Not investment advice. Generated by AI from public data; verify before acting._")
    return "\n\n".join(L) + "\n"


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("input", help="report JSON file, or - for stdin")
    p.add_argument("--out-dir", default="earnings-desk-reports")
    p.add_argument("--no-md", action="store_true")
    a = p.parse_args()
    raw = sys.stdin.read() if a.input == "-" else open(a.input).read()
    try:
        d = json.loads(raw)
    except ValueError as e:
        print(json.dumps({"error": "Invalid JSON: %s" % e}))
        sys.exit(1)
    d.setdefault("date", date.today().isoformat())
    problems = validate(d)
    with open(TEMPLATE) as f:
        tpl = f.read()
    title = "%s · %s" % (d.get("ticker", ""), re.sub(r"\*(.+?)\*", r"\1", d.get("title", "Report")))
    payload = json.dumps(d, ensure_ascii=False).replace("</", "<\\/").replace("<!--", "<\\!--")
    html_out = tpl.replace("{{TITLE}}", title.replace("<", "&lt;")).replace("{{REPORT_JSON}}", payload)
    os.makedirs(a.out_dir, exist_ok=True)
    slug = "-".join(x for x in [(d.get("ticker") or "").upper(), d.get("skill", "report"), d["date"]] if x)
    slug = re.sub(r"[^A-Za-z0-9._-]+", "-", slug)
    hp = os.path.join(a.out_dir, slug + ".html")
    with open(hp, "w") as f:
        f.write(html_out)
    out = {"html": os.path.abspath(hp), "warnings": problems}
    if not a.no_md:
        mp = os.path.join(a.out_dir, slug + ".md")
        with open(mp, "w") as f:
            f.write(to_markdown(d))
        out["markdown"] = os.path.abspath(mp)
    print(json.dumps(out, indent=2))


if __name__ == "__main__":
    main()
